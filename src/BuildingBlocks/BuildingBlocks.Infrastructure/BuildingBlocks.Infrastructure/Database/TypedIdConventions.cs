using System.Linq.Expressions;
using System.Reflection;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Microsoft.EntityFrameworkCore.Metadata.Conventions;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;

namespace BuildingBlocks.Infrastructure.Database;

/// <summary>
/// Maps every strongly typed id of a module (module rules «Strongly typed ids»): a <c>readonly record struct</c> named
/// <c>…Id</c> or <c>…Key</c> with one <c>Value</c> and a constructor taking it is stored as that value, wherever it is
/// used (key, reference, nullable reference). A whole-number id that is the key of its own table is generated by the
/// database, as a bare <c>int</c>/<c>long</c> key is, unless its configuration says <c>ValueGeneratedNever</c>.
/// The ids of the shared kernel (<c>BuildingBlocks.Domain.Identifiers</c>, ADR-0020) are mapped in every module.
/// </summary>
public static class TypedIdConventions
{
    public static ModelConfigurationBuilder AddTypedIds(this ModelConfigurationBuilder builder, Assembly domain)
    {
        var ids = TypedIds(domain).Concat(TypedIds(typeof(BuildingBlocks.Domain.MoneyAmount).Assembly)).Distinct().ToArray();
        foreach (var (id, value) in ids)
            builder.Properties(id).HaveConversion(typeof(TypedIdConverter<,>).MakeGenericType(id, value));
        var numeric = ids.Where(x => x.Value == typeof(int) || x.Value == typeof(long)).Select(x => x.Id).ToHashSet();
        builder.Conventions.Add(_ => new GeneratedNumericKeys(numeric));
        return builder;
    }

    internal static IEnumerable<(Type Id, Type Value)> TypedIds(Assembly domain) => domain.GetTypes()
        .Where(type => type is { IsValueType: true, IsPublic: true } && (type.Name.EndsWith("Id", StringComparison.Ordinal)
                       || type.Name.EndsWith("Key", StringComparison.Ordinal)))
        .Select(type => (Id: type, Value: type.GetProperty("Value")?.PropertyType))
        .Where(pair => pair.Value is not null && pair.Id.GetConstructor([pair.Value]) is not null)
        .Select(pair => (pair.Id, pair.Value!));

    /// <summary>A single whole-number typed key that is not a reference to another row is generated on add.</summary>
    private sealed class GeneratedNumericKeys(IReadOnlySet<Type> numeric) : IModelFinalizingConvention
    {
        public void ProcessModelFinalizing(IConventionModelBuilder modelBuilder,
            IConventionContext<IConventionModelBuilder> context)
        {
            foreach (var entity in modelBuilder.Metadata.GetEntityTypes())
            {
                if (entity.FindPrimaryKey() is not { Properties: [var key] } || !numeric.Contains(key.ClrType)
                    || key.GetContainingForeignKeys().Any())
                    continue;
                key.Builder.ValueGenerated(ValueGenerated.OnAdd);
            }
        }
    }

    private sealed class TypedIdConverter<TId, TValue>() : ValueConverter<TId, TValue>(ToValue(), ToId())
    {
        private static Expression<Func<TId, TValue>> ToValue()
        {
            var id = Expression.Parameter(typeof(TId), "id");
            return Expression.Lambda<Func<TId, TValue>>(Expression.Property(id, "Value"), id);
        }

        private static Expression<Func<TValue, TId>> ToId()
        {
            var value = Expression.Parameter(typeof(TValue), "value");
            return Expression.Lambda<Func<TValue, TId>>(
                Expression.New(typeof(TId).GetConstructor([typeof(TValue)])!, value), value);
        }
    }
}
